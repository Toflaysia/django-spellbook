def builtin_resources(rule, level, person):
    # Здесь числовые правила счётчиков. Полное описание умения хранится отдельно в справочнике.
    """Максимум зависит от уровня именно этого класса, а не суммарного уровня."""
    result = []

    def add(key, name, start, maximum, refresh, note):
        # Умение появляется только после достижения уровня получения.
        if level >= start:
            result.append(
                dict(
                    code=key,
                    name=name,
                    level=start,
                    maximum=maximum,
                    refresh_on=refresh,
                    note=note,
                )
            )

    charisma = (person.charisma - 10) // 2
    # Для мультикласса level — уровень именно этого класса, не общий уровень персонажа.
    if rule == "monk":
        add(
            "ki",
            "Ци",
            2,
            level,
            "short",
            f"Сл спасброска Ци: {8 + person.effective_proficiency_bonus + (person.wisdom - 10)//2}. Для восстановления нужна медитация во время отдыха.",
        )
    elif rule == "fighter":
        add(
            "second_wind",
            "Второе дыхание",
            1,
            1,
            "short",
            f"Бонусное действие: восстановить 1d10 + {level} хитов. Кнопка сама бросает кость и восстанавливает хиты.",
        )
        add(
            "action_surge",
            "Всплеск действий",
            2,
            2 if level >= 17 else 1,
            "short",
            "Дополнительное действие в свой ход; не более одного применения за ход.",
        )
        add(
            "indomitable",
            "Упорный",
            9,
            1 + (level >= 13) + (level >= 17),
            "long",
            "Переброс проваленного спасброска; нужно использовать новый результат.",
        )
    elif rule == "barbarian":
        maximum = None if level == 20 else 2 + sum(level >= n for n in (3, 6, 12, 17))
        add(
            "rage",
            "Ярость",
            1,
            maximum,
            "long",
            "Бонусное действие. Длительность и ограничения ярости отслеживаются игроком.",
        )
    elif rule == "bard":
        die = 12 if level >= 15 else 10 if level >= 10 else 8 if level >= 5 else 6
        add(
            "inspiration",
            "Вдохновение барда",
            1,
            max(1, charisma),
            "short" if level >= 5 else "long",
            f"Кость вдохновения: d{die}. Выдача кости тратит одно использование.",
        )
    elif rule == "cleric":
        add(
            "channel_divinity",
            "Божественный канал",
            2,
            1 + (level >= 6) + (level >= 18),
            "short",
            "Общий запас для вариантов Божественного канала, включая мультикласс с паладином.",
        )
    elif rule == "druid":
        add(
            "wild_shape",
            "Дикий облик",
            2,
            None if level == 20 else 2,
            "short",
            "Доступные формы и их ограничения определяются уровнем и кругом друида.",
        )
    elif rule == "paladin":
        add(
            "lay_on_hands",
            "Наложение рук",
            1,
            5 * level,
            "long",
            "Выбери число потраченных единиц. Лечение другого существа применяется на его листе; 5 единиц могут нейтрализовать яд или болезнь.",
        )
        add(
            "divine_sense",
            "Божественное чувство",
            1,
            max(0, 1 + charisma),
            "long",
            "Действие для обнаружения определённых типов существ и освящённых мест.",
        )
        add(
            "channel_divinity",
            "Божественный канал",
            3,
            1,
            "short",
            "Варианты зависят от клятвы. Запас общий с Божественным каналом жреца.",
        )
        add(
            "cleansing_touch",
            "Очищающее касание",
            14,
            max(1, charisma),
            "long",
            "Действие для прекращения заклинания на себе или согласном существе.",
        )
    elif rule == "sorcerer":
        add(
            "sorcery",
            "Единицы чародейства",
            2,
            level,
            "long",
            "Преобразование ячеек и метамагия используют этот запас. На 20-м уровне короткий отдых возвращает 4 единицы.",
        )
    elif rule == "wizard":
        add(
            "arcane_recovery",
            "Магическое восстановление",
            1,
            1,
            "manual",
            f"Один раз за день во время короткого отдыха: суммарный уровень ячеек до {(level+1)//2}, без ячеек 6-го уровня и выше. Ячейки меняются в спеллбуке.",
        )
    elif rule == "rogue":
        add(
            "stroke_of_luck",
            "Удача",
            20,
            1,
            "short",
            "Позволяет изменить промах либо результат проверки характеристики согласно описанию умения.",
        )
    elif rule == "warlock":
        for spell_level, start in ((6, 11), (7, 13), (8, 15), (9, 17)):
            add(
                f"arcanum_{spell_level}",
                f"Таинственный арканум · {spell_level}-й круг",
                start,
                1,
                "long",
                "Одно применение выбранного заклинания. Ячейки магии договора находятся в спеллбуке.",
            )
        add(
            "eldritch_master",
            "Таинственный мастер",
            20,
            1,
            "long",
            "После минуты обращения к покровителю восстанови ячейки магии договора в спеллбуке.",
        )
    return result


